def _ai_summary_table(primary_label, confidence, model_version, uncertainty, telemetry, modality="XR", severity=None) -> Table:
    tel = telemetry or {}
    loc = tel.get("anatomical_location") or "Automatic"
    diam = f"{tel.get('diameter_mm')} mm" if tel.get("diameter_mm") else "N/A"
    rows = [
        ["Primary Diagnosis", primary_label, "AI Confidence", f"{confidence * 100:.1f}%"],
        ["Location / Lobe", loc, "Uncertainty", (uncertainty or "Medium").upper()],
        ["Estimated Span", diam, "AI Model", (model_version or "DenseNet121-CheXNet")[:36]],
    ]

    # Dynamic modality-specific clinical indices
    if modality == "CT":
        f_tier = str(tel.get("fleischner_category") or "Fleischner Guideline")[:26]
        vol_str = f"{tel.get('volume_mm3', 0)} mm³" if tel.get("volume_mm3") else "Evaluated"
        rows.append(["Fleischner Tier", f_tier, "3D Voxel Vol", vol_str])
    elif modality == "MR":
        shift = f"{tel.get('midline_shift_mm', 0.0)} mm" if tel.get("midline_shift_mm") is not None else "0.0 mm"
        vol_str = f"{tel.get('volume_ml', 0)} mL" if tel.get("volume_ml") else "Calculated"
        rows.append(["Midline Shift", shift, "Lesion Volume", vol_str])
    elif modality == "US":
        birads_val = str(tel.get("birads") or "BI-RADS 4")
        ar_val = f"{tel.get('aspect_ratio', 0.0):.2f}" if tel.get("aspect_ratio") else "N/A"
        rows.append(["BI-RADS Grade", birads_val, "Aspect Ratio", ar_val])
    else:
        sev_label = (severity or "Calibrated").title()
        op_val = f"{tel.get('lung_field_opacity_pct', 0.0):.1f}%" if tel.get("lung_field_opacity_pct") else "Preserved"
        rows.append(["Severity Level", sev_label, "Lung Opacity", op_val])

    table = Table(rows, colWidths=[1.4 * inch, 2.0 * inch, 1.3 * inch, 1.8 * inch])
    table.setStyle(TableStyle([
        ("BACKGROUND", (0, 0), (0, -1), colors.HexColor("#eff6ff")),
        ("BACKGROUND", (2, 0), (2, -1), colors.HexColor("#eff6ff")),
        ("FONTNAME", (0, 0), (0, -1), "Helvetica-Bold"),
        ("FONTNAME", (2, 0), (2, -1), "Helvetica-Bold"),
        ("FONTSIZE", (0, 0), (-1, -1), 8.5),
        ("GRID", (0, 0), (-1, -1), 0.5, colors.HexColor("#bfdbfe")),
        ("LEFTPADDING", (0, 0), (-1, -1), 6),
        ("TOPPADDING", (0, 0), (-1, -1), 4),
        ("BOTTOMPADDING", (0, 0), (-1, -1), 4),
    ]))
    return table


def _findings_table(all_findings: list[dict] | None) -> Table | None:
    if not all_findings:
        return None
    data = [["Detected Condition", "Probability", "Status", "Clinical Urgency"]]
    for f in all_findings[:6]:
        data.append([
            f.get("condition", "—"),
            f"{f.get('probability', 0) * 100:.1f}%",
            f.get("status", "—").title(),
            f.get("urgency", "—").title(),
        ])
    table = Table(data, colWidths=[2.3 * inch, 1.1 * inch, 1.3 * inch, 1.8 * inch])
    table.setStyle(TableStyle([
        ("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#0f4c81")),
        ("TEXTCOLOR", (0, 0), (-1, 0), colors.white),
        ("FONTNAME", (0, 0), (-1, 0), "Helvetica-Bold"),
        ("FONTSIZE", (0, 0), (-1, -1), 8.5),
        ("GRID", (0, 0), (-1, -1), 0.5, colors.HexColor("#cbd5e1")),
        ("ROWBACKGROUNDS", (0, 1), (-1, -1), [colors.white, colors.HexColor("#f8fafc")]),
        ("LEFTPADDING", (0, 0), (-1, -1), 6),
        ("TOPPADDING", (0, 0), (-1, -1), 4),
        ("BOTTOMPADDING", (0, 0), (-1, -1), 4),
    ]))
    return table


def generate_report(
    primary_label: str,
    confidence: float,
    differential: list[dict] | None = None,
    output_dir: str = '',
    study_id: int = 0,
    severity: str | None = None,
    all_findings: list[dict] | None = None,
    extra: str = "",
    modality: str = "XR",
    patient_name: str | None = None,
    patient_age: int | None = None,
    patient_gender: str | None = None,
    model_version: str | None = None,
    uncertainty_level: str | None = None,
    original_filename: str | None = None,
    study_date: datetime | None = None,
    telemetry: dict[str, Any] | None = None,
) -> dict:
    """Generate dynamic, individualized radiology report and PDF."""
    effective_severity = severity
    if effective_severity is None:
        effective_severity = determine_severity(
            primary_label=primary_label,
            confidence=confidence,
            telemetry=telemetry,
            modality=modality,
        )

    findings = _build_dynamic_findings(
        modality=modality,
        primary_label=primary_label,
        confidence=confidence,
        telemetry=telemetry,
        all_findings=all_findings,
        extra=extra,
        model_version=model_version,
    )

    impression = _build_dynamic_impression(
        modality=modality,
        primary_label=primary_label,
        confidence=confidence,
        severity=effective_severity,
        all_findings=all_findings,
        telemetry=telemetry,
        model_version=model_version,
    )

    meta = {
        "study_id": study_id,
        "patient_name": patient_name or "Not recorded",
        "patient_age": patient_age if patient_age is not None else "—",
        "patient_gender": (patient_gender or "—").upper() if patient_gender else "—",
        "modality_label": modality,
        "exam_title": MODALITY_TITLES.get(modality, modality),
        "accession": f"RAI-{study_id:06d}",
        "filename": original_filename or "—",
        "report_date": (study_date or datetime.utcnow()).strftime("%d %b %Y %H:%M UTC"),
    }

    pdf_path = _export_pdf(
        findings=findings,
        impression=impression,
        output_dir=output_dir,
        study_id=study_id,
        all_findings=all_findings,
        modality=modality,
        meta=meta,
        primary_label=primary_label,
        confidence=confidence,
        model_version=model_version,
        uncertainty_level=uncertainty_level,
        telemetry=telemetry,
        severity=effective_severity,
    )

    return {"findings": findings, "impression": impression, "pdf_path": pdf_path}


def _export_pdf(
    findings: str,
    impression: str,
    output_dir: str,
    study_id: int,
    all_findings=None,
    modality="XR",
    meta=None,
    primary_label="",
    confidence=0.0,
    model_version=None,
    uncertainty_level=None,
    telemetry=None,
    severity=None,
) -> str:
    out_path = Path(output_dir) / f"report_{study_id}.pdf"
    out_path.parent.mkdir(parents=True, exist_ok=True)

    doc = SimpleDocTemplate(
        str(out_path),
        pagesize=letter,
        leftMargin=0.75 * inch,
        rightMargin=0.75 * inch,
        topMargin=0.60 * inch,
        bottomMargin=0.60 * inch,
    )
    styles = _build_styles()
    meta = meta or {}

    story = [
        Paragraph(INSTITUTION, styles["title"]),
        Paragraph(SUBTITLE, styles["subtitle"]),
        HRFlowable(width="100%", thickness=1.5, color=colors.HexColor("#0f4c81")),
        Spacer(1, 8),
        Paragraph(f"<b>DIAGNOSTIC RADIOLOGY REPORT — {MODALITY_TITLES.get(modality, modality).upper()}</b>", styles["section"]),
        Spacer(1, 3),
        _patient_table(meta, styles),
        Spacer(1, 10),
        Paragraph("AI QUANTITATIVE & TELEMETRY SUMMARY", styles["section"]),
        _ai_summary_table(primary_label, confidence, model_version, uncertainty_level, telemetry, modality=modality, severity=severity),
        Spacer(1, 10),
        Paragraph("CLINICAL INDICATION & TECHNIQUE", styles["section"]),
        Paragraph(MODALITY_TECHNIQUES.get(modality, "Diagnostic medical imaging study with AI assistance."), styles["body"]),
        Spacer(1, 8),
        Paragraph("FINDINGS", styles["section"]),
        Paragraph(findings, styles["body"]),
        Spacer(1, 8),
    ]

    table = _findings_table(all_findings)
    if table:
        story += [
            Paragraph("DIFFERENTIAL DIAGNOSIS BREAKDOWN (AI DETECTED)", styles["section"]),
            table,
            Spacer(1, 8),
        ]

    story += [
        Paragraph("IMPRESSION & CLINICAL ACTION PLAN", styles["section"]),
        Paragraph(impression, styles["body"]),
        Spacer(1, 14),
        HRFlowable(width="100%", thickness=0.5, color=colors.HexColor("#cbd5e1")),
        Spacer(1, 6),
        Paragraph(
            "<b>Electronically Compiled Preliminary Report</b> — Awaiting licensed radiologist verification & digital signature<br/>"
            "Attending Radiologist: ____________________________________ &nbsp;&nbsp;&nbsp;&nbsp; Date / Time: ________________________",
            styles["small"],
        ),
        Spacer(1, 8),
        Paragraph(DISCLAIMER, styles["disclaimer"]),
    ]

    doc.build(story)
    return str(out_path)
